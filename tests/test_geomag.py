@pytest.mark.parametrize("row", WMM2025_TEST)
def test_wmm2025_official_test_values(row):
    year, h, lat, lon, D, I, X, Y, Z = row
    f = geomag.field(lat, lon, h, year)
    assert f["D"] == pytest.approx(D, abs=0.006)        # fisierul are 2 zecimale
    assert f["I"] == pytest.approx(I, abs=0.006)
    assert (f["X"], f["Y"], f["Z"]) == (pytest.approx(X, abs=0.01), pytest.approx(Y, abs=0.01), pytest.approx(Z, abs=0.01))


def test_wmm_validity_and_romania():
    assert geomag.valid(2026.9) and not geomag.valid(2031.0)
    assert 6.0 < geomag.declination(45.27, 28.46, 0.0, 2026.87) < 7.5


def test_geoid_regional_grid():
    assert geoid.undulation(45.27, 28.46) == pytest.approx(32.26, abs=0.02)
    assert geoid.undulation(44.43, 26.10) == pytest.approx(34.70, abs=0.02)
    assert geoid.undulation(52.0, 10.0) is None
    assert geoid.hae_to_msl(45.27, 28.46, 100.0) == pytest.approx(100.0 - 32.26, abs=0.02)
    assert geoid.msl_to_hae(45.27, 28.46, geoid.hae_to_msl(45.27, 28.46, 100.0)) == pytest.approx(100.0)


def test_sapient_magnetic_bearing_corrected_with_wmm():
    FR = LocalFrame(45.27, 28.46)
    lat, lon = FR.to_latlon(0.0, 0.0)
    year = 2026.87
    ad = UniversalAdapter(sites=[RadarSite("mag", lat, lon)], frame=FR, tod_ref=36000.0, decimal_year=year)
    msg = {"timestamp": "2026-11-12T10:00:05Z", "nodeId": "mag", "detectionReport": {"rangeBearing": {
        "azimuth": 0.0, "range": 5000.0, "coordinateSystem": "RANGE_BEARING_COORDINATE_SYSTEM_DEGREES_M",
        "datum": "RANGE_BEARING_DATUM_MAGNETIC"}}}
    out = ad.feed(json.dumps(msg))
    x, y = FR.to_xy(out[0].lat, out[0].lon)
    decl = geomag.declination(lat, lon, 0.0, year)
    assert math.degrees(math.atan2(x, y)) == pytest.approx(decl, abs=0.05)   # nord magnetic -> adevarat
    assert any("WMM2025" in n for n in ad.sources["SAPIENT:mag"].notes)
